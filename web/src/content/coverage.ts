import skillMap from "../../../src/platy/skills/data/skill_map.json";
import { DEMO_NODES, LEVELS } from "../mock/generate";
import { CATALOG, type ItemDescriptor, type Role, ROLES } from "./catalog";
import { REPAIRS_TO_BUILD, SLIPS } from "./slips";

// The content coverage grid (R-37): skill-map nodes × roles, each cell the items whose primary
// skill is that node. It's computed from the catalog and the skill map every time and never
// kept by hand: `npm --prefix web run coverage` writes it to docs/content/coverage.md, and
// coverage.test.ts fails when that file is stale. Pure: no I/O here.

export const GENERATED_LINE = "Generated by `npm --prefix web run coverage`; don't edit.";

export interface CoverageInputs {
  /** The skill map's nodes, in map order. */
  nodes: readonly { id: string; name: string }[];
  items: readonly ItemDescriptor[];
  slips: readonly { id: string; node: string; repair: string }[];
  /** Repair items slips point at that don't exist yet. */
  toBuild: ReadonlySet<string>;
  /** Nodes with a problem generator (R-41), which counts as practice at its levels. */
  generators: readonly { node: string; levels: readonly number[] }[];
  /** The demo path's nodes: their gaps are listed first. */
  demo: readonly string[];
}

export interface Cell {
  node: string;
  role: Role;
  /** Item ids, sorted. */
  items: string[];
  /** The generator's levels, on a practice cell of a node that has one. */
  generator: readonly number[] | null;
}

export interface Coverage {
  rows: { node: string; name: string; cells: Cell[] }[];
  /** Cells filled by an item or a generator, out of nodes × roles. */
  filled: number;
  /** The demo path's empty cells, in map order. */
  demoGaps: { node: string; name: string; roles: Role[] }[];
  /** Slips whose repair item doesn't exist. */
  slipsWithoutRepair: { id: string; node: string; repair: string }[];
  /** Nodes whose items all take one angle (an R-05 retry has nowhere else to go). */
  oneAngle: { node: string; name: string; angle: string }[];
}

export const isEmpty = (c: Cell): boolean => c.items.length === 0 && c.generator === null;

export function coverage(inputs: CoverageInputs): Coverage {
  const generators = new Map(inputs.generators.map((g) => [g.node, g.levels]));
  const ids = new Set(inputs.items.map((i) => i.id));
  const rows = inputs.nodes.map((n) => ({
    node: n.id,
    name: n.name,
    cells: ROLES.map((role): Cell => ({
      node: n.id,
      role,
      items: inputs.items.filter((i) => i.skills.primary === n.id && i.role === role).map((i) => i.id).sort(),
      generator: role === "practice" ? (generators.get(n.id) ?? null) : null,
    })),
  }));
  const demoGaps = rows
    .filter((r) => inputs.demo.includes(r.node))
    .map((r) => ({ node: r.node, name: r.name, roles: r.cells.filter(isEmpty).map((c) => c.role) }))
    .filter((g) => g.roles.length > 0);
  const slipsWithoutRepair = inputs.slips
    .filter((s) => inputs.toBuild.has(s.repair) || !ids.has(s.repair))
    .map(({ id, node, repair }) => ({ id, node, repair }));
  const oneAngle = inputs.nodes.flatMap((n) => {
    const angles = new Set(inputs.items.filter((i) => i.skills.primary === n.id).map((i) => i.angle));
    return angles.size === 1 ? [{ node: n.id, name: n.name, angle: [...angles][0]! }] : [];
  });
  const filled = rows.flatMap((r) => r.cells).filter((c) => !isEmpty(c)).length;
  return { rows, filled, demoGaps, slipsWithoutRepair, oneAngle };
}

/** Cells with more ids than this show a count, with the ids in a footnote. */
const INLINE = 2;

export function renderCoverage(c: Coverage, itemCount: number): string {
  const footnotes: string[] = [];
  const levels = (l: readonly number[]) => (l.length === 1 ? `L${l[0]}` : `L${l[0]}–L${l[l.length - 1]}`);
  const cell = (x: Cell): string => {
    const parts: string[] = [];
    if (x.generator) parts.push(`generator ${levels(x.generator)}`);
    if (x.items.length > INLINE) {
      footnotes.push(x.items.join(", "));
      parts.push(`${x.items.length} items[^${footnotes.length}]`);
    } else parts.push(...x.items);
    return parts.length === 0 ? "—" : parts.join(", ");
  };
  const total = c.rows.length * ROLES.length;
  const lines = [
    "# Content coverage",
    "",
    GENERATED_LINE,
    "",
    "Skill-map nodes in map order, one column per role. A cell lists the items whose primary skill is the row",
    "(`web/src/content/catalog.json`, R-37); `generator` is the mock's problem generator (R-41) at its levels;",
    "— is empty.",
    "",
    `${itemCount} items; ${c.filled} of ${total} cells filled.`,
    "",
    `| Skill | ${ROLES.join(" | ")} |`,
    `|---|${ROLES.map(() => "---").join("|")}|`,
    ...c.rows.map((r) => `| **${r.name}**<br>\`${r.node}\` | ${r.cells.map(cell).join(" | ")} |`),
    "",
    "## Demo-path gaps",
    "",
    ...list(c.demoGaps.map((g) => `**${g.name}** (\`${g.node}\`): ${g.roles.join(", ")}`)),
    "",
    "## Slips with no repair",
    "",
    ...list(c.slipsWithoutRepair.map((s) => `\`${s.id}\` (${s.node}) points at \`${s.repair}\``)),
    "",
    "## Skills with one angle",
    "",
    ...list(c.oneAngle.map((n) => `**${n.name}** (\`${n.node}\`): ${n.angle}`)),
  ];
  if (footnotes.length > 0) lines.push("", ...footnotes.map((f, i) => `[^${i + 1}]: ${f}`));
  return `${lines.join("\n")}\n`;
}

const list = (items: string[]) => (items.length === 0 ? ["None."] : items.map((i) => `- ${i}`));

/** What the grid is built from today. */
export function defaultInputs(): CoverageInputs {
  return {
    nodes: skillMap.nodes,
    items: CATALOG,
    slips: SLIPS,
    toBuild: REPAIRS_TO_BUILD,
    generators: DEMO_NODES.map((node) => ({ node, levels: LEVELS })),
    demo: DEMO_NODES,
  };
}

/** docs/content/coverage.md, as the script writes it. */
export function coverageMarkdown(): string {
  const inputs = defaultInputs();
  return renderCoverage(coverage(inputs), inputs.items.length);
}
